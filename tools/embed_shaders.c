// Build-time tool: turns shader files into a C header so warp.exe needs no
// resources folder.  usage: embed_shaders out.h file1 file2 ...
// The renderer prefers files on disk (for F5 hot reload) and falls back to these.
#include <stdio.h>
#include <string.h>

int main(int argc, char** argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s out.h files...\n", argv[0]); return 1; }
    FILE* out = fopen(argv[1], "wb");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "// generated by tools/embed_shaders.c -- do not edit\n");
    fprintf(out, "typedef struct { const char* name; const char* src; } EmbeddedShader;\n");
    fprintf(out, "static const EmbeddedShader EMBEDDED_SHADERS[] = {\n");
    for (int i = 2; i < argc; i++) {
        FILE* f = fopen(argv[i], "rb");
        if (!f) { perror(argv[i]); fclose(out); return 1; }
        const char* base = argv[i];
        for (const char* p = argv[i]; *p; p++) if (*p == '/' || *p == '\\') base = p + 1;
        fprintf(out, "  { \"%s\",\n    \"", base);
        int c;
        while ((c = fgetc(f)) != EOF) {
            if (c == '\r') continue;
            if (c == '\n') fputs("\\n\"\n    \"", out);
            else if (c == '"' || c == '\\') fprintf(out, "\\%c", c);
            else if (c == '\t') fputs("    ", out);
            else fputc(c, out);
        }
        fputs("\" },\n", out);
        fclose(f);
    }
    fprintf(out, "};\n#define EMBEDDED_SHADER_COUNT %d\n", argc - 2);
    fclose(out);
    return 0;
}
